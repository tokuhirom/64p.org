SKIP = re.compile(r'^<iframe ')  # デモはそのまま
src = open('main.txt').read()
slides = src.split('\n----\n')
missing = []
out = []
for sl in slides:
    lines = [l for l in sl.split('\n') if not l.startswith('<div class="en">')]
    vis = [l for l in lines if l.strip() and not l.startswith('<!--') and not l.startswith('<div style')]
    key = vis[0] if vis else ''
    # 時間配分コメントなど複数行コメントの中身は無視
    if key.startswith(' ') or key == '':
        out.append('\n'.join(lines)); continue
    if SKIP.match(key):
        out.append('\n'.join(lines)); continue
    en = EN.get(key)
    if en is None:
        missing.append(key)
        out.append('\n'.join(lines)); continue
    if en == '':
        out.append('\n'.join(lines)); continue
    # 先頭スライドは複数行コメントがあるので、コメントの前に入れる
    if lines and lines[0] == key and any(l.startswith('<!--') and not l.endswith('-->') for l in lines):
        i = next(i for i, l in enumerate(lines) if l.startswith('<!--'))
        lines.insert(i, f'<div class="en">{en}</div>')
    else:
        while lines and lines[-1] == '':
            lines.pop()
        lines.append(f'<div class="en">{en}</div>')
    out.append('\n'.join(lines))
if missing:
    print('未訳:', *missing, sep='\n  ')
